"""Generate the Hebrew fold's Default_Ignorable_Code_Point range table.

Run with the project's Python so its Unicode database selects the release::

    python scripts/generate_default_ignorable_table.py --download

The complete, unmodified Unicode data file is retained for offline checking.
"""

from __future__ import annotations

import argparse
import hashlib
import unicodedata
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render(data: bytes, version: str) -> str:
    """Render every property range, including its unassigned code points."""

    text = data.decode("utf-8")
    if not text.startswith(f"# DerivedCoreProperties-{version}.txt\n"):
        raise ValueError(f"data file is not Unicode {version}")
    ranges = []
    for line in text.splitlines():
        fields = line.split("#", 1)[0].split(";")
        if len(fields) != 2 or fields[1].strip() != "Default_Ignorable_Code_Point":
            continue
        limits = fields[0].strip().split("..")
        ranges.append((int(limits[0], 16), int(limits[-1], 16)))
    if not ranges:
        raise ValueError("data file contains no Default_Ignorable_Code_Point ranges")
    digest = hashlib.sha256(data).hexdigest()
    return (
        '"""Generated Unicode property data; regenerate with the script below."""\n\n'
        "# Generated by scripts/generate_default_ignorable_table.py.\n"
        f"# Unicode version: {version}\n"
        f"# Source: https://www.unicode.org/Public/{version}/ucd/DerivedCoreProperties.txt\n"
        f"# Source SHA-256: {digest}\n"
        f'UNICODE_VERSION = "{version}"\n'
        f'DERIVED_CORE_PROPERTIES_SHA256 = (\n    "{digest}"\n)\n'
        "DEFAULT_IGNORABLE_RANGES: tuple[tuple[int, int], ...] = (\n"
        + "".join(f"    (0x{low:04X}, 0x{high:04X}),\n" for low, high in ranges)
        + ")\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--unicode-version", default=unicodedata.unidata_version)
    parser.add_argument("--data-file", type=Path)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--download", action="store_true")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    version = args.unicode_version
    data_file = args.data_file or (
        ROOT / "tests" / "fixtures" / "unicode" / f"DerivedCoreProperties-{version}.txt"
    )
    output = args.output or (
        ROOT
        / "src"
        / "axiom_encode"
        / "harness"
        / f"_unicode_default_ignorables_{version.replace('.', '_')}.py"
    )
    if args.download:
        url = f"https://www.unicode.org/Public/{version}/ucd/DerivedCoreProperties.txt"
        with urllib.request.urlopen(url, timeout=60) as response:
            data = response.read()
        # Validate before replacing the offline copy.
        render(data, version)
        data_file.parent.mkdir(parents=True, exist_ok=True)
        data_file.write_bytes(data)
    expected = render(data_file.read_bytes(), version)
    if args.check:
        if output.read_text() != expected:
            parser.error(f"{output} differs; regenerate from {data_file}")
    else:
        output.write_text(expected)


if __name__ == "__main__":
    main()
