@dataclass(frozen=True)
class MhrtcBranchRole:
    inventory_kind: str
    source_span: tuple[int, int]
    classification: str
    roles: tuple[str, ...]
    rules: tuple[str, ...]


def mhrtc_branch_roles(bound, content, source, *, formulas, controls, exceptions):
    """Match all typed production branches before selecting static source roles.

    Full-source controls still require every substantive witness. Static role
    assignment cannot certify a caller's execution or satisfy a source gate.
    """
    from .source_completeness import SourceStructureBranch

    current = bind_mhrtc_program(content, source)
    if current is None or current != bound:
        raise ValueError("complete current source/formula binding required")
    supplied = {
        "formula_branches": formulas,
        "control_branches": controls,
        "exception_branches": exceptions,
    }
    actual = []
    for category, branches in supplied.items():
        if type(branches) not in (list, tuple):
            raise ValueError("complete branch sequence required")
        for branch in branches:
            if type(branch) is not SourceStructureBranch:
                raise ValueError("actual typed source branches required")
            actual.append((category, _typed(asdict(branch))))
    expected = []
    result = []
    for category, declaration, classification, roles, rules in _BRANCHES:
        record = dict(declaration)
        record["text"] = source[record["start"] : record["end"]]
        expected.append((category, _typed(record)))
        result.append(
            MhrtcBranchRole(
                category,
                (record["start"], record["end"]),
                classification,
                roles,
                rules,
            )
        )
    if Counter(actual) != Counter(expected):
        raise ValueError("complete typed source branch multiset differs")
    return tuple(result)
