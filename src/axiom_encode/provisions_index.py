"""Byte-exact replica of a RuleSpec repo's provision -> rules reverse index.

rulespec-<country> keeps ``.axiom/index/provisions_to_rules.json``, derived
from the tracked RuleSpec YAML by the repository's own
``tests/generate_reverse_index.py``; its CI regenerates the file on every pull
request and fails when the committed copy differs. Signed model applies never
write the file, so every encoder pull request that adds a citation failed that
check until someone regenerated the index by hand.

The protected publish step must not run checkout code (it holds a repository
write token), so this module reproduces the generator instead. It only
answers for a tree whose generator blob is one of
:data:`SUPPORTED_GENERATOR_BLOBS`, the exact versions reproduced here. Any
other generator, and any tree shape the generator would read differently from
a Git tree (symlinked modules or jurisdiction roots, initialized submodules,
non-UTF-8 modules, a citation-bearing module whose YAML crashes the loader
rather than failing to parse), raises
:class:`UnsupportedIndexTree` so the caller leaves the index alone.

The index is derived metadata: no signed manifest, receipt, or the
generated-provenance guard binds it, and rulespec CI recomputes it from the
YAML, so a wrong regeneration can only fail the same check that fails today.
"""

from __future__ import annotations

import json
import subprocess
from collections.abc import Iterable
from pathlib import Path, PurePosixPath
from typing import Any

import yaml

INDEX_PATH = PurePosixPath(".axiom/index/provisions_to_rules.json")
GENERATOR_PATH = PurePosixPath("tests/generate_reverse_index.py")
# Git blob ids of rulespec generator versions this module reproduces byte for
# byte (rulespec-us 326de2b768, 2026-07-16, current as of 2026-10-15).
SUPPORTED_GENERATOR_BLOBS = frozenset({"aa8f9738041c19440b01c54a2e649c911e679bc9"})
INDEX_SCHEMA = "axiom.rulespec.provisions_to_rules/v1"
INDEX_DESCRIPTION = (
    "Reverse index from corpus citation path to the RuleSpec modules "
    "that depend on it (module source_verification and proof-atom "
    "sources). Generated by tests/generate_reverse_index.py; do not "
    "edit by hand."
)
MODULE_REFERENCE = "module"
PROOF_ATOM_REFERENCE = "proof_atom"
MODULE_SUFFIXES = (".yaml", ".yml")
TEST_SUFFIXES = (".test.yaml", ".test.yml")


class UnsupportedIndexTree(ValueError):
    """The tree is not one this replica can index exactly like the generator."""


def is_jurisdiction_dir(name: str) -> bool:
    """Match the generator's ``validate-roots: auto`` directory convention."""

    if not name or name.startswith((".", "_")):
        return False
    segments = name.split("-")
    if len(segments[0]) != 2 or not segments[0].isalpha() or not segments[0].islower():
        return False
    for segment in segments[1:]:
        if not segment or not all(
            ch.isalnum() and (ch.islower() or ch.isdigit()) for ch in segment
        ):
            return False
    return True


def is_module_name(name: str) -> bool:
    return name.endswith(MODULE_SUFFIXES) and not name.endswith(TEST_SUFFIXES)


def _clean_citation_path(value: Any) -> str | None:
    if not isinstance(value, str):
        return None
    cleaned = value.strip()
    return cleaned or None


def citation_paths_for_module(payload: Any) -> dict[str, set[str]]:
    """Return ``{citation_path: {reference_kind, ...}}`` for one module."""

    references: dict[str, set[str]] = {}
    if not isinstance(payload, dict):
        return references
    module = payload.get("module")
    if isinstance(module, dict):
        verification = module.get("source_verification")
        if isinstance(verification, dict):
            citations = [verification.get("corpus_citation_path")]
            plural_citations = verification.get("corpus_citation_paths")
            if isinstance(plural_citations, list):
                citations.extend(plural_citations)
            for value in citations:
                citation = _clean_citation_path(value)
                if citation is not None:
                    references.setdefault(citation, set()).add(MODULE_REFERENCE)
    rules = payload.get("rules")
    if isinstance(rules, list):
        for rule in rules:
            if not isinstance(rule, dict):
                continue
            metadata = rule.get("metadata")
            if not isinstance(metadata, dict):
                continue
            proof = metadata.get("proof")
            if not isinstance(proof, dict):
                continue
            atoms = proof.get("atoms")
            if not isinstance(atoms, list):
                continue
            for atom in atoms:
                if not isinstance(atom, dict):
                    continue
                source = atom.get("source")
                if not isinstance(source, dict):
                    continue
                citation = _clean_citation_path(source.get("corpus_citation_path"))
                if citation is not None:
                    references.setdefault(citation, set()).add(PROOF_ATOM_REFERENCE)
    return references


def _module_text(path: str, raw: bytes) -> str:
    """Decode like ``Path.read_text(encoding="utf-8")`` (universal newlines)."""

    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        # The generator does not catch this: its run would crash.
        raise UnsupportedIndexTree(f"module is not UTF-8: {path}") from exc
    return text.replace("\r\n", "\n").replace("\r", "\n")


def may_reference_citations(text: str) -> bool:
    """Whether parsing ``text`` could yield a ``corpus_citation_path(s)`` key.

    A YAML key's characters come from the source either literally or through
    backslash escapes in double-quoted scalars; folding only ever adds
    spaces. So a module whose text has neither the literal key stem nor any
    backslash cannot reference a provision, and skipping its parse cannot
    change the index (it is a large speed-up: most modules are tables).
    """

    return "corpus_citation_path" in text or "\\" in text


def build_index(
    modules: Iterable[tuple[str, bytes]], *, prefilter: bool = True
) -> dict[str, Any]:
    """Build the index from ``(repo-relative module path, bytes)`` pairs.

    With ``prefilter`` (the default) modules that cannot reference a
    provision are decoded but not parsed; ``prefilter=False`` parses every
    module exactly as the generator does. Both give the same index whenever
    the generator itself completes.
    """

    provisions: dict[str, dict[str, set[str]]] = {}
    module_count = 0
    for module_path, raw in sorted(modules):
        text = _module_text(module_path, raw)
        if prefilter and not may_reference_citations(text):
            continue
        try:
            payload = yaml.safe_load(text)
        except yaml.YAMLError:
            continue
        except Exception as exc:  # the generator would crash, not skip
            raise UnsupportedIndexTree(
                f"module cannot be loaded like the generator loads it: {module_path}"
            ) from exc
        references = citation_paths_for_module(payload)
        if not references:
            continue
        module_count += 1
        for citation, kinds in references.items():
            provisions.setdefault(citation, {}).setdefault(module_path, set()).update(
                kinds
            )
    edge_count = 0
    provisions_out: dict[str, Any] = {}
    for citation in sorted(provisions):
        module_map = provisions[citation]
        modules_out = [
            {"module": module_path, "via": sorted(module_map[module_path])}
            for module_path in sorted(module_map)
        ]
        edge_count += len(modules_out)
        provisions_out[citation] = modules_out
    return {
        "schema": INDEX_SCHEMA,
        "description": INDEX_DESCRIPTION,
        "counts": {
            "provisions": len(provisions_out),
            "edges": edge_count,
            "modules": module_count,
        },
        "provisions": provisions_out,
    }


def render_index(index: dict[str, Any]) -> bytes:
    """Serialize exactly as the generator writes the file (UTF-8, no counts)."""

    serializable = {key: value for key, value in index.items() if key != "counts"}
    text = json.dumps(serializable, indent=2, ensure_ascii=False, sort_keys=False)
    return (text + "\n").encode("utf-8")


def _git(repo: Path, *args: str, stdin: bytes | None = None) -> bytes:
    return subprocess.run(
        [
            "git",
            "--no-replace-objects",
            "--literal-pathspecs",
            "-c",
            "core.hooksPath=/dev/null",
            "-C",
            str(repo),
            *args,
        ],
        check=True,
        capture_output=True,
        input=stdin,
    ).stdout


def tree_entries(repo: Path, commit: str) -> list[tuple[str, str, str, str]]:
    """Return ``(mode, type, object, path)`` for every entry in a commit tree."""

    entries: list[tuple[str, str, str, str]] = []
    for record in _git(repo, "ls-tree", "-r", "-t", "-z", "--full-tree", commit).split(
        b"\0"
    ):
        if not record:
            continue
        metadata, separator, raw_path = record.partition(b"\t")
        fields = metadata.decode("ascii").split(" ")
        if not separator or len(fields) != 3:
            raise UnsupportedIndexTree("tree listing is malformed")
        try:
            path = raw_path.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise UnsupportedIndexTree("tree path is not UTF-8") from exc
        entries.append((fields[0], fields[1], fields[2], path))
    return entries


def module_objects(entries: Iterable[tuple[str, str, str, str]]) -> dict[str, str]:
    """Select the module blobs the generator would read from a checkout.

    The generator walks top-level directories named like jurisdictions with
    ``rglob("*.yaml")``/``rglob("*.yml")`` (Python 3.13+, so symlinked
    directories are not traversed) and reads every regular non-test match.
    """

    entries = list(entries)
    roots: set[str] = set()
    for mode, _object_type, _object_id, path in entries:
        if "/" in path or not is_jurisdiction_dir(path):
            continue
        if mode == "040000":
            roots.add(path)
        elif mode in {"120000", "160000"}:
            raise UnsupportedIndexTree(f"jurisdiction root is not a directory: {path}")
    modules: dict[str, str] = {}
    for mode, object_type, object_id, path in entries:
        top, separator, _rest = path.partition("/")
        if not separator or top not in roots:
            continue
        name = PurePosixPath(path).name
        if mode == "160000":
            raise UnsupportedIndexTree(f"submodule inside a jurisdiction: {path}")
        if not is_module_name(name):
            continue
        if mode == "120000":
            raise UnsupportedIndexTree(f"symlinked RuleSpec module: {path}")
        if object_type == "blob" and mode in {"100644", "100755"}:
            modules[path] = object_id
    return modules


def read_blobs(repo: Path, object_ids: Iterable[str]) -> dict[str, bytes]:
    """Read many blobs through one ``git cat-file --batch`` process."""

    ordered = sorted(set(object_ids))
    if not ordered:
        return {}
    output = _git(
        repo,
        "cat-file",
        "--batch",
        stdin="".join(f"{oid}\n" for oid in ordered).encode(),
    )
    blobs: dict[str, bytes] = {}
    position = 0
    for oid in ordered:
        newline = output.index(b"\n", position)
        header = output[position:newline].decode("ascii").split(" ")
        if len(header) != 3 or header[0] != oid or header[1] != "blob":
            raise UnsupportedIndexTree(f"object is not a readable blob: {oid}")
        size = int(header[2])
        start = newline + 1
        blobs[oid] = output[start : start + size]
        position = start + size + 1
    return blobs


def regenerate_from_commit(repo: Path, commit: str, *, prefilter: bool = True) -> bytes:
    """Return the exact index bytes the tree's own generator would write."""

    entries = tree_entries(repo, commit)
    generator = [
        (mode, object_id)
        for mode, object_type, object_id, path in entries
        if path == GENERATOR_PATH.as_posix() and object_type == "blob"
    ]
    if len(generator) != 1 or generator[0][1] not in SUPPORTED_GENERATOR_BLOBS:
        raise UnsupportedIndexTree(
            "tests/generate_reverse_index.py is absent or not a reproduced version"
        )
    modules = module_objects(entries)
    blobs = read_blobs(repo, modules.values())
    return render_index(
        build_index(
            ((path, blobs[object_id]) for path, object_id in modules.items()),
            prefilter=prefilter,
        )
    )


REFRESH_SCHEMA = "axiom-encode/provisions-index-refresh/v1"
RECEIPT_ROOTS = (
    PurePosixPath(".axiom/legacy-replacements"),
    PurePosixPath(".axiom/path-migrations"),
    PurePosixPath(".axiom/retired-source-metadata-migrations"),
)
LANE_BRANCH_PREFIX = "refs/heads/axiom/signed-backfill-"
REFRESH_COMMIT_SUBJECT = "Regenerate the provision-to-rules reverse index (unsigned)"


def _commit(repo: Path, revision: str) -> str:
    return (
        _git(repo, "rev-parse", "--verify", f"{revision}^{{commit}}").decode().strip()
    )


def _index_blob(entries: Iterable[tuple[str, str, str, str]]) -> str | None:
    matches = [
        (mode, object_type, object_id)
        for mode, object_type, object_id, path in entries
        if path == INDEX_PATH.as_posix()
    ]
    if len(matches) != 1 or matches[0][:2] != ("100644", "blob"):
        return None
    return matches[0][2]


def refresh_lane_index(repo: Path, lane_base: str) -> dict[str, Any]:
    """Append one unsigned commit that brings the reverse index up to date.

    ``lane_base`` is the commit the signed lane sits on (the pull request base
    the lane was published onto). The index is left alone when the tree does
    not track it, when any lane commit already changes it (legacy replacements
    sign it as an applied file), when the tree's generator is not a reproduced
    version, or when the tree has a shape the replica does not reproduce. The
    new commit changes exactly the index path and nothing else.
    """

    head = _commit(repo, "HEAD")
    evidence: dict[str, Any] = {
        "schema": REFRESH_SCHEMA,
        "index_path": INDEX_PATH.as_posix(),
        "lane_base": lane_base,
        "head_before": head,
        "head_after": head,
        "index_blob_before": None,
        "index_blob_after": None,
        "mode": "current",
        "reason": None,
    }

    def skip(mode: str, reason: str) -> dict[str, Any]:
        evidence.update({"mode": mode, "reason": reason})
        return evidence

    branch = _git(repo, "symbolic-ref", "-q", "HEAD").decode().strip()
    if not branch.startswith(LANE_BRANCH_PREFIX):
        raise ValueError("reverse index refresh requires the signed lane branch")
    if _git(repo, "status", "--porcelain=v1", "-z", "--untracked-files=all"):
        raise ValueError("reverse index refresh requires a clean lane checkout")
    lane_base = _commit(repo, lane_base)
    lane_commits = _git(repo, "rev-list", f"{lane_base}..{head}").decode().split()
    is_ancestor = subprocess.run(
        ["git", "-C", str(repo), "merge-base", "--is-ancestor", lane_base, head],
        check=False,
        capture_output=True,
    )
    if not lane_commits or is_ancestor.returncode != 0:
        raise ValueError("reverse index refresh found no signed lane commits")
    entries = tree_entries(repo, head)
    current = _index_blob(entries)
    evidence["index_blob_before"] = current
    evidence["index_blob_after"] = current
    if current is None:
        return skip("skipped-absent", "the tree does not track the reverse index")
    lane_paths: set[PurePosixPath] = set()
    for commit in lane_commits:
        commit_paths = {
            PurePosixPath(raw.decode("utf-8"))
            for raw in _git(
                repo,
                "diff-tree",
                "-r",
                "-z",
                "--no-renames",
                "--name-only",
                f"{commit}^",
                commit,
            ).split(b"\0")
            if raw
        }
        subject = _git(repo, "log", "-1", "--format=%s", commit).decode().strip()
        if commit_paths == {INDEX_PATH} and subject == REFRESH_COMMIT_SUBJECT:
            continue  # an earlier refresh of this lane, not a signed change
        lane_paths.update(commit_paths)
    if INDEX_PATH in lane_paths:
        return skip("skipped-signed", "a signed lane commit already changes the index")
    receipts = sorted(
        path.as_posix()
        for path in lane_paths
        if any(path.is_relative_to(root) for root in RECEIPT_ROOTS)
    )
    if receipts:
        # Receipt-bound lanes are re-proved against exact change sets and
        # receipt-computed metadata post-images; never add a path to them.
        return skip("skipped-receipt", "the lane carries receipts: " + receipts[0])
    try:
        regenerated = regenerate_from_commit(repo, head)
    except UnsupportedIndexTree as exc:
        return skip("skipped-unsupported", str(exc))
    new_blob = (
        _git(repo, "hash-object", "-w", "--no-filters", "--stdin", stdin=regenerated)
        .decode()
        .strip()
    )
    if new_blob == current:
        return evidence

    import os
    import tempfile

    identity = _git(repo, "log", "-1", "--format=%cn%x00%ce", head).decode()
    name, _separator, email = identity.rstrip("\n").partition("\0")
    environment = {
        **os.environ,
        "GIT_AUTHOR_NAME": name,
        "GIT_AUTHOR_EMAIL": email,
        "GIT_COMMITTER_NAME": name,
        "GIT_COMMITTER_EMAIL": email,
    }
    message = (
        f"{REFRESH_COMMIT_SUBJECT}\n\n"
        "Derived from the RuleSpec YAML in this tree by axiom-encode's byte-exact\n"
        "replica of tests/generate_reverse_index.py. This commit is not signed\n"
        "and no apply manifest covers it; rulespec CI regenerates the index\n"
        "from the YAML and compares it.\n"
    ).encode()
    with tempfile.TemporaryDirectory(prefix="axiom-provisions-index-") as scratch:
        index_environment = {**environment, "GIT_INDEX_FILE": f"{scratch}/index"}
        subprocess.run(
            ["git", "--no-replace-objects", "-C", str(repo), "read-tree", head],
            check=True,
            capture_output=True,
            env=index_environment,
        )
        subprocess.run(
            [
                "git",
                "--no-replace-objects",
                "-C",
                str(repo),
                "update-index",
                "--cacheinfo",
                f"100644,{new_blob},{INDEX_PATH.as_posix()}",
            ],
            check=True,
            capture_output=True,
            env=index_environment,
        )
        tree = (
            subprocess.run(
                ["git", "--no-replace-objects", "-C", str(repo), "write-tree"],
                check=True,
                capture_output=True,
                env=index_environment,
            )
            .stdout.decode()
            .strip()
        )
    refreshed = (
        subprocess.run(
            [
                "git",
                "--no-replace-objects",
                "-c",
                "core.hooksPath=/dev/null",
                "-C",
                str(repo),
                "commit-tree",
                tree,
                "-p",
                head,
                "-F",
                "-",
            ],
            check=True,
            capture_output=True,
            input=message,
            env=environment,
        )
        .stdout.decode()
        .strip()
    )
    changed = [
        path
        for path in _git(
            repo,
            "diff-tree",
            "-r",
            "-z",
            "--no-renames",
            "--name-only",
            head,
            refreshed,
        ).split(b"\0")
        if path
    ]
    if changed != [INDEX_PATH.as_posix().encode()]:
        raise ValueError("reverse index refresh changed paths other than the index")
    _git(repo, "read-tree", "-m", "-u", head, refreshed)
    _git(
        repo,
        "update-ref",
        "-m",
        "regenerate the provision-to-rules reverse index",
        branch,
        refreshed,
        head,
    )
    if _commit(repo, "HEAD") != refreshed or _git(
        repo, "status", "--porcelain=v1", "-z", "--untracked-files=all"
    ):
        raise ValueError("lane checkout did not move to the reverse index refresh")
    evidence.update(
        {"mode": "refreshed", "head_after": refreshed, "index_blob_after": new_blob}
    )
    return evidence


def regenerate_from_directory(repo_root: Path, *, prefilter: bool = True) -> bytes:
    """Index a checkout exactly as the generator walks it (tests and audits)."""

    root = Path(repo_root).resolve()
    modules: list[tuple[str, bytes]] = []
    for entry in sorted(root.iterdir()):
        if not (entry.is_dir() and is_jurisdiction_dir(entry.name)):
            continue
        for pattern in ("*.yaml", "*.yml"):
            for path in entry.rglob(pattern):
                if path.is_file() and not path.name.endswith(TEST_SUFFIXES):
                    modules.append(
                        (path.relative_to(root).as_posix(), path.read_bytes())
                    )
    return render_index(build_index(modules, prefilter=prefilter))
