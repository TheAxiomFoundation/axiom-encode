@pytest.fixture(autouse=True)
def _system_git(monkeypatch):
    """Use the same root-owned Git admitted by the production supervisor."""

    monkeypatch.setenv("PATH", "/usr/bin" + os.pathsep + os.environ["PATH"])


def _guard(fixture, monkeypatch, *, repo=None, **options):
    repo = fixture.repo if repo is None else repo
    tools = repo.parent / "retired-receipt-trusted-tools"
    if not tools.exists():
        tools.mkdir()
        _install_trusted_git_wrapper(
            tools, Path(sys.executable).resolve(), Path("/usr/bin/git")
        )
    with monkeypatch.context() as wrapped:
        wrapped.setenv("PATH", str(tools) + os.pathsep + os.environ["PATH"])
        return cli.guard_generated_change_issues(
            repo, corpus_path=fixture.corpus, **options
        )


def _active_refresh(fixture):
    _set_producer_identity(fixture.payload, dict(TEST_PINNED_ENCODER_IDENTITY))
    cli._sign_applied_encoding_manifest(fixture.payload, fixture.broker)
    fixture.manifest.write_text(json.dumps(fixture.payload) + "\n")
    return _commit(fixture.repo, "active-root manifest-only refresh")


@pytest.mark.parametrize("all_files", (False, True), ids=("diff", "all-with-base"))
def test_manifest_only_active_root_refresh_accepts_retired_base(
    frozen_repo, monkeypatch, all_files
):
    """Refresh preserves generated bytes while replacing the retired signature."""

    fixture = frozen_repo
    _active_refresh(fixture)
    assert cli._git_changed_files(
        fixture.repo, base_ref=fixture.cutoff, head_ref="HEAD"
    ) == [fixture.manifest_relative]
    assert (
        _guard(
            fixture,
            monkeypatch,
            base_ref=fixture.cutoff,
            all_files=all_files,
        )
        == []
    )


def test_retrospective_range_modifying_frozen_manifest(frozen_repo, monkeypatch):
    """A pre-cutoff rewrite has the same payload in both immutable envelopes."""

    fixture = frozen_repo
    rewritten = fixture.manifest_bytes + b"\n"
    fixture.manifest.write_bytes(rewritten)
    cutoff = _commit(fixture.repo, "frozen manifest rewritten before cutoff")
    inventory = copy.deepcopy(fixture.broker.retired_apply_inventory)
    repository = inventory["repositories"][0]
    repository["cutoff_commit"] = cutoff
    repository["artifacts"][0]["sha256"] = hashlib.sha256(rewritten).hexdigest()
    broker = _RotatedBroker(inventory)
    monkeypatch.setattr(cli, "_applied_encoding_manifest_verifier", lambda: broker)
    monkeypatch.setattr(cli, "get_signing_broker", lambda **_kwargs: broker)

    assert cli._git_changed_files(
        fixture.repo, base_ref=fixture.cutoff, head_ref="HEAD"
    ) == [fixture.manifest_relative]
    assert (
        _guard(
            fixture,
            monkeypatch,
            base_ref=fixture.cutoff,
            head_ref=cutoff,
            retrospective=True,
        )
        == []
    )


def test_deleted_retired_base_receipt_is_authenticated(frozen_repo, monkeypatch):
    """A deleted receipt supplies evidence only; it grants no head authority."""

    fixture = frozen_repo
    relative = cli.APPLIED_ENCODING_LEGACY_REPLACEMENT_RECEIPT_DIR / "frozen.json"
    receipt = fixture.repo / relative
    receipt.parent.mkdir(parents=True)
    # Deletion checks authenticate the immutable receipt envelope. A receipt
    # with no surviving owner has no replacement proof to replay at the head.
    payload = dict.fromkeys(cli._LEGACY_REPLACEMENT_RECEIPT_FIELDS)
    payload.update(
        schema_version=cli.APPLIED_ENCODING_LEGACY_REPLACEMENT_RECEIPT_SCHEMA,
        tool=cli.APPLIED_ENCODING_LEGACY_REPLACEMENT_TOOL,
    )
    cli._sign_applied_encoding_manifest(payload, TEST_APPLY_SIGNING_BROKER)
    receipt.write_text(json.dumps(payload) + "\n")
    receipt.chmod(0o644)
    cutoff = _commit(fixture.repo, "freeze historical auxiliary envelope")
    broker = _RotatedBroker(_freeze_artifacts(fixture.repo, cutoff, fixture.old_head))
    monkeypatch.setattr(cli, "_applied_encoding_manifest_verifier", lambda: broker)
    monkeypatch.setattr(cli, "get_signing_broker", lambda **_kwargs: broker)
    receipt.unlink()
    _commit(fixture.repo, "remove unused historical auxiliary receipt")

    assert _guard(fixture, monkeypatch, base_ref=cutoff) == []


def test_retrospective_claimant_load_uses_ancestor_head(frozen_repo, monkeypatch):
    """The head claimant is frozen at a strict ancestor of the owner cutoff."""

    fixture = frozen_repo
    fixture.manifest.write_bytes(fixture.manifest_bytes + b"\n")
    audited_head = _commit(fixture.repo, "rewrite historical claimant envelope")
    (fixture.repo / "README.md").write_text("Later owner cutoff.\n")
